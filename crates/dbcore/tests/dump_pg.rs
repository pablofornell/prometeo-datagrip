//! PostgreSQL whole-schema dump / restore round-trip. Run with:
//!   PROMETEO_PG_URL=postgres://postgres:prometeo@localhost:54329/postgres cargo test -p dbcore --test dump_pg -- --nocapture

mod common;

use common::*;
use dbcore::import::CancellationToken;
use dbcore::*;
use serde_json::json;

/// Self-contained schema built on a placeholder schema name (no enums / matviews / functions, so the
/// dump never has to deal with out-of-scope objects).
const SEED: &str = r#"
create table __SCHEMA__.parents (
    id serial primary key,
    name text not null unique,
    amount numeric(12,2) not null default 0,
    check (length(name) > 0)
);
create table __SCHEMA__.children (
    id bigint generated by default as identity primary key,
    parent_id integer not null references __SCHEMA__.parents (id),
    label text,
    tags text[],
    unique (parent_id, label)
);
create index idx_children_parent on __SCHEMA__.children (parent_id);
create sequence __SCHEMA__.standalone_seq start with 100 increment by 5;
create view __SCHEMA__.v_children as
    select c.id, p.name as parent, c.label from __SCHEMA__.children c join __SCHEMA__.parents p on p.id = c.parent_id;
insert into __SCHEMA__.parents (name, amount) values ('Alpha', 10.50), ('Bêta', 20.25);
insert into __SCHEMA__.children (parent_id, label, tags) values (1, 'c1', array['a','b']), (2, 'héllo', array['x']);
"#;

async fn seed(mgr: &ConnectionManager, s: &SessionId, src: &str, dst: &str) {
    assert_ok(
        &run(
            mgr,
            s,
            &format!("drop schema if exists {dst} cascade; drop schema if exists {src} cascade; create schema {src};"),
        )
        .await,
    );
    assert_ok(&run(mgr, s, &SEED.replace("__SCHEMA__", src)).await);
}

/// Dumps `src` into `dst` (via `target_schema`) and restores it, returning the dump text.
async fn dump_and_restore(
    mgr: &ConnectionManager,
    s: &SessionId,
    src: &str,
    dst: &str,
    data: bool,
) -> String {
    let mut buf = Vec::new();
    let cancel = CancellationToken::new();
    let res = mgr
        .dump_schema(
            "pg",
            src,
            &DumpOptions {
                data,
                target_schema: Some(dst.into()),
                ..Default::default()
            },
            &cancel,
            &|_| {},
            &mut buf,
        )
        .await
        .unwrap();
    assert_eq!(res.tables, 2);
    assert_eq!(res.rows, if data { 4 } else { 0 });
    assert!(!res.cancelled);
    let dump = String::from_utf8(buf).unwrap();

    assert_ok(&run(mgr, s, &format!("create schema {dst}")).await);
    let ev = mgr
        .execute_collect(
            s,
            &dump,
            ExecOptions {
                max_rows: 10,
                stop_on_error: true,
                ..Default::default()
            },
        )
        .await
        .unwrap();
    assert_ok(&ev);
    dump
}

/// The table names of `schema`, sorted.
async fn tables(mgr: &ConnectionManager, s: &SessionId, schema: &str) -> Vec<String> {
    let sql =
        format!("select tablename from pg_tables where schemaname = '{schema}' order by tablename");
    first_rs(&run(mgr, s, &sql).await)
        .1
        .into_iter()
        .map(|r| r[0].as_str().unwrap().to_string())
        .collect()
}

#[tokio::test]
async fn dump_restore_round_trip() {
    let Some(cfg) = pg_cfg() else {
        eprintln!("PROMETEO_PG_URL not set: skipping");
        return;
    };
    let mgr = &connected(&cfg).await;
    let s = mgr.open_session("pg").await.unwrap();
    let (src, dst) = ("dump_src", "dump_dst");
    seed(mgr, &s, src, dst).await;

    let dump = dump_and_restore(mgr, &s, src, dst, true).await;

    // the schema prefix is renamed everywhere it matters
    for needle in [
        "\"dump_dst\".\"parents\"",
        "nextval('dump_dst.parents_id_seq'::regclass)",
        "references dump_dst.parents",
        "on dump_dst.children",
    ] {
        assert!(dump.contains(needle), "missing {needle:?} in:\n{dump}");
    }
    assert!(!dump.contains("dump_src"), "source schema leaked:\n{dump}");

    // identical table inventory
    assert_eq!(tables(mgr, &s, src).await, tables(mgr, &s, dst).await);
    assert_eq!(
        tables(mgr, &s, dst).await,
        vec!["children".to_string(), "parents".to_string()]
    );

    // identical row counts
    for t in ["parents", "children"] {
        assert_eq!(
            scalar(&run(mgr, &s, &format!("select count(*) from {src}.{t}")).await),
            scalar(&run(mgr, &s, &format!("select count(*) from {dst}.{t}")).await),
            "row count of {t}"
        );
    }

    // data spot checks: unicode text, numeric-as-text, array literal
    assert_eq!(
        first_rs(
            &run(
                mgr,
                &s,
                &format!("select name, amount from {dst}.parents order by id")
            )
            .await
        )
        .1,
        vec![
            vec![json!("Alpha"), json!("10.50")],
            vec![json!("Bêta"), json!("20.25")],
        ]
    );
    assert_eq!(
        first_rs(
            &run(
                mgr,
                &s,
                &format!("select tags from {dst}.children where id = 1")
            )
            .await
        )
        .1,
        vec![vec![json!(["a", "b"])]]
    );

    // serial and identity sequences are resynced to max(id) => the next value is 3
    assert_eq!(
        scalar(&run(mgr, &s, &format!("select nextval('{dst}.parents_id_seq')")).await),
        json!(3)
    );
    assert_eq!(
        scalar(&run(mgr, &s, &format!("select nextval('{dst}.children_id_seq')")).await),
        json!(3)
    );

    // the view was restored and is queryable
    assert_eq!(
        first_rs(&run(mgr, &s, &format!("select count(*) from {dst}.v_children")).await).1,
        vec![vec![json!(2)]]
    );

    // constraints actually enforced
    let ev = run(
        mgr,
        &s,
        &format!("insert into {dst}.children (parent_id, label) values (99, 'orphan')"),
    )
    .await;
    assert!(
        errors(&ev)[0].contains("violates foreign key constraint"),
        "{:?}",
        errors(&ev)
    );
    let ev = run(
        mgr,
        &s,
        &format!("insert into {dst}.parents (name, amount) values ('Alpha', 1)"),
    )
    .await;
    assert!(
        errors(&ev)[0].contains("duplicate key"),
        "{:?}",
        errors(&ev)
    );

    assert_ok(
        &run(
            mgr,
            &s,
            &format!("drop schema if exists {src} cascade; drop schema if exists {dst} cascade;"),
        )
        .await,
    );
    mgr.close_session(&s).await;
}

/// A schema-only dump (`data: false`) creates the objects but leaves them empty.
#[tokio::test]
async fn schema_only_dump_omits_data() {
    let Some(cfg) = pg_cfg() else {
        eprintln!("PROMETEO_PG_URL not set: skipping");
        return;
    };
    let mgr = &connected(&cfg).await;
    let s = mgr.open_session("pg").await.unwrap();
    let (src, dst) = ("dump_src_b", "dump_dst_b");
    seed(mgr, &s, src, dst).await;

    let dump = dump_and_restore(mgr, &s, src, dst, false).await;
    assert!(!dump.contains("insert into"), "{dump}");

    assert_eq!(
        scalar(&run(mgr, &s, &format!("select count(*) from {dst}.parents")).await),
        json!(0)
    );
    assert_eq!(
        scalar(&run(mgr, &s, &format!("select count(*) from {dst}.children")).await),
        json!(0)
    );

    assert_ok(
        &run(
            mgr,
            &s,
            &format!("drop schema if exists {src} cascade; drop schema if exists {dst} cascade;"),
        )
        .await,
    );
    mgr.close_session(&s).await;
}

/// Dumps `src` with `opts` (target `dst`) and returns the text.
async fn dump_text(
    mgr: &ConnectionManager,
    src: &str,
    dst: &str,
    opts: DumpOptions,
) -> (String, DumpResult) {
    let mut buf = Vec::new();
    let res = mgr
        .dump_schema(
            "pg",
            src,
            &DumpOptions {
                target_schema: Some(dst.into()),
                ..opts
            },
            &CancellationToken::new(),
            &|_| {},
            &mut buf,
        )
        .await
        .unwrap();
    (String::from_utf8(buf).unwrap(), res)
}

async fn restore_text(mgr: &ConnectionManager, s: &SessionId, dump: &str) {
    let ev = mgr
        .execute_collect(
            s,
            dump,
            ExecOptions {
                max_rows: 10,
                stop_on_error: true,
                ..Default::default()
            },
        )
        .await
        .unwrap();
    assert_ok(&ev);
}

async fn count(mgr: &ConnectionManager, s: &SessionId, table: &str) -> serde_json::Value {
    scalar(&run(mgr, s, &format!("select count(*) from {table}")).await)
}

async fn cleanup(mgr: &ConnectionManager, s: &SessionId, schemas: &[&str]) {
    for sc in schemas {
        assert_ok(&run(mgr, s, &format!("drop schema if exists {sc} cascade")).await);
    }
}

/// `drop_if_exists` makes a restore repeatable (tables, sequences and views are dropped with `cascade`), and
/// the sequences a column default needs are written even with `include_sequences` off.
#[tokio::test]
async fn drop_if_exists_restore_twice_and_serial_sequences_without_include_sequences() {
    let Some(cfg) = pg_cfg() else {
        eprintln!("PROMETEO_PG_URL not set: skipping");
        return;
    };
    let mgr = &connected(&cfg).await;
    let s = mgr.open_session("pg").await.unwrap();
    let (src, dst) = ("dump_src_c", "dump_dst_c");
    seed(mgr, &s, src, dst).await;

    for include_sequences in [false, true] {
        cleanup(mgr, &s, &[dst]).await;
        assert_ok(&run(mgr, &s, &format!("create schema {dst}")).await);
        let (dump, res) = dump_text(
            mgr,
            src,
            dst,
            DumpOptions {
                drop_if_exists: true,
                include_sequences,
                ..Default::default()
            },
        )
        .await;
        assert_eq!((res.tables, res.rows), (2, 4));
        assert!(
            dump.contains("drop table if exists \"dump_dst_c\".\"parents\" cascade;")
                || dump.contains("drop table if exists dump_dst_c.parents cascade;"),
            "{dump}"
        );
        assert!(
            dump.contains("drop view if exists") && dump.contains("cascade;"),
            "{dump}"
        );
        assert!(dump.contains("drop sequence if exists"), "{dump}");
        // the serial sequence is always created; the standalone one only on request
        assert!(
            dump.contains("create sequence") && dump.contains("parents_id_seq"),
            "{dump}"
        );
        assert_eq!(dump.contains("standalone_seq"), include_sequences, "{dump}");

        // twice into the same target: the second run drops what the first one made
        restore_text(mgr, &s, &dump).await;
        restore_text(mgr, &s, &dump).await;
        assert_eq!(count(mgr, &s, &format!("{dst}.parents")).await, json!(2));
        assert_eq!(count(mgr, &s, &format!("{dst}.children")).await, json!(2));
        assert_eq!(
            first_rs(
                &run(
                    mgr,
                    &s,
                    &format!("select name from {dst}.parents order by id")
                )
                .await
            )
            .1,
            vec![vec![json!("Alpha")], vec![json!("Bêta")]]
        );
        // the serial default works (sequence exists, resynced)
        assert_ok(
            &run(
                mgr,
                &s,
                &format!("insert into {dst}.parents (name) values ('Gamma')"),
            )
            .await,
        );
        assert_eq!(
            scalar(&run(mgr, &s, &format!("select max(id) from {dst}.parents")).await),
            json!(3)
        );
    }
    cleanup(mgr, &s, &[src, dst]).await;
    mgr.close_session(&s).await;
}

/// `tables` limits the dump to a subset (foreign keys to tables left out are skipped), `include_ddl = false`
/// writes only data and the sequence resync, `commit_every` adds commits; progress names the table.
#[tokio::test]
async fn table_subset_data_only_commits_and_progress_table() {
    let Some(cfg) = pg_cfg() else {
        eprintln!("PROMETEO_PG_URL not set: skipping");
        return;
    };
    let mgr = &connected(&cfg).await;
    let s = mgr.open_session("pg").await.unwrap();
    let (src, dst) = ("dump_src_d", "dump_dst_d");
    seed(mgr, &s, src, dst).await;

    // children only: no view, no `parents_id_seq`, no foreign key to the table that is left out
    assert_ok(&run(mgr, &s, &format!("create schema {dst}")).await);
    let (dump, res) = dump_text(
        mgr,
        src,
        dst,
        DumpOptions {
            tables: Some(vec!["children".into()]),
            include_routines: true,
            ..Default::default()
        },
    )
    .await;
    assert_eq!((res.tables, res.rows), (1, 2));
    assert!(
        !dump.contains("parents")
            && !dump.contains("v_children")
            && !dump.contains("standalone_seq"),
        "{dump}"
    );
    restore_text(mgr, &s, &dump).await;
    assert_eq!(count(mgr, &s, &format!("{dst}.children")).await, json!(2));
    assert_eq!(
        scalar(&run(mgr, &s, &format!("select count(*) from pg_indexes where schemaname = '{dst}' and indexname = 'idx_children_parent'")).await),
        json!(1),
        "the indexes of the subset come along"
    );
    cleanup(mgr, &s, &[dst]).await;

    // both tables restored, then dumped data only (with commits) into the emptied tables
    assert_ok(&run(mgr, &s, &format!("create schema {dst}")).await);
    let (full, _) = dump_text(mgr, src, dst, DumpOptions::default()).await;
    restore_text(mgr, &s, &full).await;
    assert_ok(&run(mgr, &s, &format!("truncate {dst}.children, {dst}.parents")).await);
    let seen = std::sync::Mutex::new(Vec::<Option<String>>::new());
    let mut buf = Vec::new();
    let res = mgr
        .dump_schema(
            "pg",
            src,
            &DumpOptions {
                target_schema: Some(dst.into()),
                include_ddl: false,
                commit_every: 1,
                batch_size: 1,
                ..Default::default()
            },
            &CancellationToken::new(),
            &|p| {
                if p.phase == "data" || p.phase == "tables" {
                    seen.lock().unwrap().push(p.table)
                }
            },
            &mut buf,
        )
        .await
        .unwrap();
    assert_eq!((res.tables, res.rows), (2, 4));
    let data = String::from_utf8(buf).unwrap();
    for banned in [
        "create table",
        "create view",
        "create index",
        "create sequence",
        "alter table",
        "drop ",
    ] {
        assert!(
            !data.contains(banned),
            "{banned:?} in a data-only dump:\n{data}"
        );
    }
    assert_eq!(data.matches("commit;").count(), 4, "{data}");
    assert!(
        data.contains("setval"),
        "the sequence resync stays:\n{data}"
    );
    assert!(seen
        .lock()
        .unwrap()
        .iter()
        .any(|t| t.as_deref() == Some("parents")));
    restore_text(mgr, &s, &data).await;
    assert_eq!(count(mgr, &s, &format!("{dst}.parents")).await, json!(2));
    assert_eq!(count(mgr, &s, &format!("{dst}.children")).await, json!(2));
    assert_ok(
        &run(
            mgr,
            &s,
            &format!("insert into {dst}.parents (name) values ('Gamma')"),
        )
        .await,
    );
    assert_eq!(
        scalar(&run(mgr, &s, &format!("select max(id) from {dst}.parents")).await),
        json!(3)
    );

    cleanup(mgr, &s, &[src, dst]).await;
    mgr.close_session(&s).await;
}

/// A range-partitioned table (with a default partition): the partitions come along as `partition of`, its rows are
/// written once, through the parent, and an index on the parent is created on every partition.
#[tokio::test]
async fn partitioned_table_round_trip() {
    let Some(cfg) = pg_cfg() else {
        eprintln!("PROMETEO_PG_URL not set: skipping");
        return;
    };
    let mgr = &connected(&cfg).await;
    let s = mgr.open_session("pg").await.unwrap();
    let (src, dst) = ("dump_src_p", "dump_dst_p");
    cleanup(mgr, &s, &[dst, src]).await;
    assert_ok(&run(mgr, &s, &format!("create schema {src}")).await);
    assert_ok(
        &run(
            mgr,
            &s,
            &format!(
                "create table {src}.events (id bigint not null, created_at date not null, kind text, \
                     primary key (id, created_at)) partition by range (created_at); \
                 create table {src}.events_2024 partition of {src}.events \
                     for values from ('2024-01-01') to ('2025-01-01'); \
                 create table {src}.events_later partition of {src}.events \
                     for values from ('2025-01-01') to ('2030-01-01'); \
                 create table {src}.events_rest partition of {src}.events default; \
                 create index events_kind_idx on {src}.events (kind); \
                 insert into {src}.events values (1, '2024-03-01', 'a'), (2, '2025-05-01', 'b'), \
                     (3, '2031-01-01', 'c'), (4, '2024-07-01', 'd');"
            ),
        )
        .await,
    );

    assert_ok(&run(mgr, &s, &format!("create schema {dst}")).await);
    let (dump, res) = dump_text(mgr, src, dst, DumpOptions::default()).await;
    // one table (the partitioned one; its partitions are written with it), four rows, through the parent
    assert_eq!((res.tables, res.rows), (1, 4), "{dump}");
    for needle in [
        "partition by range (created_at);",
        "create table \"dump_dst_p\".\"events_2024\" partition of \"dump_dst_p\".\"events\" for values from ('2024-01-01') to ('2025-01-01');",
        "partition of \"dump_dst_p\".\"events\" default;",
        "create index events_kind_idx on dump_dst_p.events using btree (kind);",
    ] {
        assert!(dump.contains(needle), "missing {needle:?} in:\n{dump}");
    }
    assert!(!dump.contains("on only"), "{dump}");
    assert_eq!(
        dump.matches("insert into").count(),
        1,
        "one insert for the partitioned table:\n{dump}"
    );

    restore_text(mgr, &s, &dump).await;
    assert_eq!(
        scalar(
            &run(
                mgr,
                &s,
                &format!(
                    "select count(*) from pg_inherits where inhparent = '{dst}.events'::regclass"
                )
            )
            .await
        ),
        json!(3)
    );
    assert_eq!(count(mgr, &s, &format!("{dst}.events")).await, json!(4));
    assert_eq!(
        count(mgr, &s, &format!("{dst}.events_2024")).await,
        json!(2)
    );
    assert_eq!(
        count(mgr, &s, &format!("{dst}.events_later")).await,
        json!(1)
    );
    assert_eq!(
        count(mgr, &s, &format!("{dst}.events_rest")).await,
        json!(1)
    );
    // the index went on the parent and on each partition
    assert_eq!(
        scalar(
            &run(
                mgr,
                &s,
                &format!("select count(*) from pg_indexes where schemaname = '{dst}' and indexdef like '%(kind)%'")
            )
            .await
        ),
        json!(4)
    );
    // rows route to the partitions: 2032 is in none of them but the default one
    assert_ok(
        &run(
            mgr,
            &s,
            &format!("insert into {dst}.events values (5, '2032-01-01', 'e')"),
        )
        .await,
    );
    assert_eq!(
        count(mgr, &s, &format!("{dst}.events_rest")).await,
        json!(2)
    );

    cleanup(mgr, &s, &[src, dst]).await;
    mgr.close_session(&s).await;
}

/// A foreign table is not dumped: a comment and a warning name it. (file_fdw is installed for the test, and removed
/// again when this test installed it.)
#[tokio::test]
async fn foreign_table_is_skipped_with_a_warning() {
    let Some(cfg) = pg_cfg() else {
        eprintln!("PROMETEO_PG_URL not set: skipping");
        return;
    };
    let mgr = &connected(&cfg).await;
    let s = mgr.open_session("pg").await.unwrap();
    let (src, dst) = ("dump_src_f", "dump_dst_f");
    cleanup(mgr, &s, &[dst, src]).await;
    let had_fdw = scalar(
        &run(
            mgr,
            &s,
            "select count(*) from pg_extension where extname = 'file_fdw'",
        )
        .await,
    ) != json!(0);
    assert_ok(&run(mgr, &s, "create extension if not exists file_fdw").await);
    assert_ok(
        &run(
            mgr,
            &s,
            &format!(
                "create schema {src}; \
                 create server dump_fdw_srv foreign data wrapper file_fdw; \
                 create foreign table {src}.remote_log (line text) server dump_fdw_srv options (filename '/dev/null');"
            ),
        )
        .await,
    );

    assert_ok(&run(mgr, &s, &format!("create schema {dst}")).await);
    let (dump, res) = dump_text(mgr, src, dst, DumpOptions::default()).await;
    assert!(
        dump.contains("-- foreign table remote_log: not dumped"),
        "{dump}"
    );
    assert!(
        res.warnings
            .iter()
            .any(|w| w == "foreign table remote_log: not dumped"),
        "{:?}",
        res.warnings
    );
    assert_eq!((res.tables, res.rows), (0, 0));
    restore_text(mgr, &s, &dump).await;
    assert_eq!(
        scalar(&run(mgr, &s, &format!("select count(*) from pg_class c join pg_namespace n on n.oid = c.relnamespace where n.nspname = '{dst}' and c.relname = 'remote_log'")).await),
        json!(0)
    );

    cleanup(mgr, &s, &[src, dst]).await;
    assert_ok(&run(mgr, &s, "drop server if exists dump_fdw_srv cascade").await);
    if !had_fdw {
        assert_ok(&run(mgr, &s, "drop extension if exists file_fdw").await);
    }
    mgr.close_session(&s).await;
}
